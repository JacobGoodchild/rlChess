#!/usr/bin/env python3
"""Writes src/RlChess.Web/wwwroot/css/pieces.css: one block of CSS per piece-set folder in wwwroot/pieces.

Each set folder holds wK.svg ... bP.svg (any of .svg/.png). Run this after adding a set, and add the
set to Settings.PieceSets in src/RlChess.Web/Game/Settings.cs.
"""
from pathlib import Path

root = Path(__file__).resolve().parent.parent / "src" / "RlChess.Web" / "wwwroot"
out = ["/* Generated by tools/make-piece-css.py: do not edit by hand. */"]
for folder in sorted(p for p in (root / "pieces").iterdir() if p.is_dir()):
    s = folder.name
    for color in "wb":
        for kind in "KQRBNP":
            files = [f for f in folder.iterdir() if f.stem == color + kind]
            if not files:
                raise SystemExit(f"{folder} is missing {color}{kind}")
            out.append(f'.pieces-{s} .piece.{color}{kind} {{ background-image: url("../pieces/{s}/{files[0].name}"); }}')
    wk = next(f.name for f in folder.iterdir() if f.stem == "wK")
    bk = next(f.name for f in folder.iterdir() if f.stem == "bK")
    out.append(f'.pieces-{s} .piece.half {{ background-image: url("../pieces/{s}/{wk}"); }}')
    out.append(f'.pieces-{s} .piece.half::after {{ background-image: url("../pieces/{s}/{bk}"); }}')
(root / "css" / "pieces.css").write_text("\n".join(out) + "\n")
print(f"Wrote {root / 'css' / 'pieces.css'}")
